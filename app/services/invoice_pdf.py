"""Generate branded PDF invoices using fpdf2."""

import io
import logging
from typing import Any

from app.services.pdf_brand import (
    GOLD,
    NAVY,
    NAVY_50,
    NAVY_100,
    NAVY_500,
    NAVY_900,
    WHITE,
    BrandedPDF,
    draw_header,
    eyebrow,
    fit,
    info_card,
    safe,
)

logger = logging.getLogger(__name__)


def generate_invoice_pdf(
    invoice_number: str,
    student_name: str,
    due_date: str,
    total_amount: str,
    currency: str,
    line_items: list[dict[str, Any]],
    tenant_name: str,
    tenant_address: str | None = None,
    tenant_phone: str | None = None,
    tenant_email: str | None = None,
    banking_details: str | None = None,
    payment_instructions: str | None = None,
    amount_paid: Any = None,
    balance_due: Any = None,
) -> bytes:
    """Generate a PDF invoice and return the bytes.

    ``amount_paid`` / ``balance_due`` are optional (backward-compatible):
    when given, the PDF shows Total / Amount paid / Balance due and a
    clear PAID state at a zero balance. Values are read from the stored
    invoice — no calculation happens here. Without them the PDF shows
    the total as the amount due (the send-time case: nothing paid yet).
    """
    show_payments = amount_paid is not None or balance_due is not None
    total_num = _num(total_amount)
    paid_num = _num(amount_paid) if amount_paid is not None else 0.0
    balance_num = _num(balance_due) if balance_due is not None else total_num - paid_num
    is_paid = show_payments and balance_num <= 0
    pdf = BrandedPDF(footer_text=f"Generated by ClassUp on behalf of {safe(tenant_name)}")
    pdf.set_auto_page_break(auto=True, margin=22)
    pdf.add_page()

    address = " ".join(
        ln.strip() for ln in (tenant_address or "").splitlines() if ln.strip()
    )
    contact = "  |  ".join(
        p for p in (
            f"Tel {tenant_phone}" if tenant_phone else "",
            tenant_email or "",
        ) if p
    )
    draw_header(
        pdf,
        org_name=tenant_name,
        org_lines=[address, contact],
        doc_title="INVOICE",
        doc_subtitle=invoice_number,
    )

    content_w = pdf.w - pdf.l_margin - pdf.r_margin
    top = pdf.get_y()

    # --- Billed to (left) ---
    eyebrow(pdf, "Billed to", pdf.l_margin, top)
    pdf.set_xy(pdf.l_margin, top + 5)
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(*NAVY_900)
    pdf.cell(content_w * 0.5, 7, fit(pdf, student_name, content_w * 0.5))
    eyebrow(pdf, "Invoice number", pdf.l_margin, top + 16)
    pdf.set_xy(pdf.l_margin, top + 21)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(*NAVY_900)
    pdf.cell(content_w * 0.5, 5, safe(invoice_number))

    # --- Amount due card (right) ---
    card_w = 72
    card_x = pdf.w - pdf.r_margin - card_w
    pdf.set_fill_color(*NAVY_50)
    pdf.rect(card_x, top - 2, card_w, 30, style="F", round_corners=True, corner_radius=3)
    pdf.set_fill_color(*GOLD)
    pdf.rect(card_x, top - 2, 1.4, 30, style="F")
    if is_paid:
        eyebrow(pdf, "Status", card_x + 6, top + 2)
        card_big = "PAID"
        card_small = f"Total {money(currency, total_num)} paid in full"
    else:
        eyebrow(pdf, "Balance due" if show_payments else "Amount due", card_x + 6, top + 2)
        card_big = money(currency, balance_num if show_payments else total_num)
        card_small = f"Due {due_date}"
    pdf.set_xy(card_x + 6, top + 7)
    pdf.set_font("Helvetica", "B", 17)
    pdf.set_text_color(*NAVY)
    pdf.cell(card_w - 10, 9, fit(pdf, card_big, card_w - 10))
    pdf.set_xy(card_x + 6, top + 18)
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*NAVY_500)
    pdf.cell(card_w - 10, 5, fit(pdf, card_small, card_w - 10))

    pdf.set_xy(pdf.l_margin, top + 38)

    # --- Line items ---
    col_desc = content_w * 0.52
    col_qty = content_w * 0.10
    col_unit = content_w * 0.19
    col_total = content_w - col_desc - col_qty - col_unit

    def table_header() -> None:
        pdf.set_font("Helvetica", "B", 8)
        pdf.set_fill_color(*NAVY)
        pdf.set_text_color(*WHITE)
        pdf.cell(col_desc, 9, "  DESCRIPTION", fill=True)
        pdf.cell(col_qty, 9, "QTY", fill=True, align="C")
        pdf.cell(col_unit, 9, "UNIT PRICE", fill=True, align="R")
        pdf.cell(col_total, 9, "AMOUNT  ", fill=True, align="R")
        pdf.ln()
        pdf.set_text_color(*NAVY_900)

    table_header()
    pdf.set_font("Helvetica", "", 9.5)
    row_h = 8.5
    for i, item in enumerate(line_items):
        if pdf.get_y() + row_h > pdf.h - pdf.b_margin:
            pdf.add_page()
            table_header()
            pdf.set_font("Helvetica", "", 9.5)
        fill = i % 2 == 1
        pdf.set_fill_color(*NAVY_50)
        desc = fit(pdf, item.get("description", ""), col_desc - 6)
        pdf.cell(col_desc, row_h, f"  {desc}", fill=fill)
        pdf.cell(col_qty, row_h, safe(item.get("quantity", 1)), fill=fill, align="C")
        pdf.cell(col_unit, row_h, safe(money(currency, item.get('unit_amount', 0))), fill=fill, align="R")
        pdf.cell(col_total, row_h, safe(money(currency, item.get('total_amount', 0)) + "  "), fill=fill, align="R")
        pdf.ln()

    pdf.set_draw_color(*NAVY_100)
    pdf.set_line_width(0.3)
    y = pdf.get_y()
    pdf.line(pdf.l_margin, y, pdf.w - pdf.r_margin, y)

    # --- Totals ---
    rows: list[tuple[str, str, bool]] = []
    if show_payments:
        rows.append(("TOTAL", money(currency, total_num), False))
        rows.append(("AMOUNT PAID", money(currency, paid_num), False))
        rows.append(("BALANCE DUE", "PAID" if is_paid else money(currency, balance_num), True))
    else:
        rows.append(("TOTAL DUE", money(currency, total_num), True))
    needed = 8 + 9 * len(rows)
    if pdf.get_y() + needed > pdf.h - pdf.b_margin:
        pdf.add_page()
    pdf.ln(4)
    tot_w = col_unit + col_total
    tot_x = pdf.w - pdf.r_margin - tot_w
    y = pdf.get_y()
    pdf.set_draw_color(*GOLD)
    pdf.set_line_width(0.6)
    pdf.line(tot_x, y, pdf.w - pdf.r_margin, y)
    row_y = y + 2
    for label, value, strong in rows:
        pdf.set_xy(tot_x, row_y)
        pdf.set_font("Helvetica", "B", 9)
        pdf.set_text_color(*NAVY_500)
        pdf.cell(col_unit, 8, label)
        pdf.set_font("Helvetica", "B", 12 if strong else 10)
        pdf.set_text_color(*NAVY)
        pdf.cell(col_total, 8, safe(value + "  "), align="R")
        row_y += 9
    pdf.set_text_color(0, 0, 0)
    pdf.set_xy(pdf.l_margin, row_y + 6)

    if banking_details and banking_details.strip():
        info_card(pdf, "Banking details", banking_details)
    if payment_instructions and payment_instructions.strip():
        info_card(pdf, "Payment instructions", payment_instructions)

    buf = io.BytesIO()
    pdf.output(buf)
    return buf.getvalue()


def _num(val: Any) -> float:
    try:
        return float(str(val).replace(",", ""))
    except (TypeError, ValueError):
        return 0.0


def money(currency: str | None, val: Any) -> str:
    """"$1,100.00" for a symbol; "USD 1,100.00" for a letter code."""
    cur = (currency or "").strip()
    amount = _num(val)
    sign = "-" if amount < 0 else ""
    num = f"{abs(amount):,.2f}"
    if not cur:
        return f"{sign}{num}"
    if cur.isalpha() and len(cur) == 3:
        return f"{sign}{cur} {num}"
    return f"{sign}{cur}{num}"


def _fmt(val: Any) -> str:
    """Format a numeric value to 2 decimal places."""
    try:
        return f"{float(val):.2f}"
    except (TypeError, ValueError):
        return str(val)
