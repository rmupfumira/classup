"""Shared ClassUp brand chrome for fpdf2 documents (invoices, report-card
fallback): navy header band with the logo, gold accent rule, rounded
info cards and a page footer. Colours mirror the Soft Modern tokens in
base.html.
"""

from __future__ import annotations

from pathlib import Path

from fpdf import FPDF

NAVY = (27, 58, 107)          # #1B3A6B
NAVY_900 = (14, 27, 52)       # #0e1b34
NAVY_500 = (58, 95, 150)      # #3a5f96
NAVY_200 = (194, 210, 231)    # #c2d2e7
NAVY_100 = (227, 235, 245)    # #e3ebf5
NAVY_50 = (244, 247, 251)     # #f4f7fb
GOLD = (201, 150, 42)         # #C9962A
GOLD_600 = (160, 116, 32)     # #a07420
GOLD_50 = (253, 249, 236)     # #fdf9ec
WHITE = (255, 255, 255)

LOGO_PATH = (
    Path(__file__).resolve().parent.parent / "static" / "img" / "icons" / "icon-192.png"
)

HEADER_H = 36.0


class BrandedPDF(FPDF):
    """A4 FPDF with a branded footer (generated-by line + page x of y)."""

    def __init__(self, footer_text: str = "Generated by ClassUp"):
        super().__init__(format="A4")
        self.footer_text = footer_text
        self.set_margins(16, 16, 16)
        self.alias_nb_pages()

    def footer(self) -> None:
        self.set_y(-14)
        self.set_draw_color(*NAVY_100)
        self.set_line_width(0.2)
        self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
        self.ln(2.5)
        self.set_font("Helvetica", "", 7.5)
        self.set_text_color(*NAVY_500)
        self.cell(0, 4, self.footer_text)
        self.set_x(self.l_margin)
        self.cell(0, 4, f"Page {self.page_no()} of {{nb}}", align="R")
        self.set_text_color(0, 0, 0)


def safe(text: object) -> str:
    """Core PDF fonts are latin-1 only; swap common typographic characters
    and drop anything else so a stray emoji can't crash the render."""
    s = str(text if text is not None else "")
    s = (
        s.replace("—", "-").replace("–", "-")
        .replace("’", "'").replace("‘", "'")
        .replace("“", '"').replace("”", '"')
        .replace("…", "...")
    )
    return s.encode("latin-1", "replace").decode("latin-1")


def fit(pdf: FPDF, text: str, width: float) -> str:
    """Truncate ``text`` with an ellipsis so it fits ``width`` at the
    current font."""
    text = safe(text)
    if pdf.get_string_width(text) <= width:
        return text
    while text and pdf.get_string_width(text + "...") > width:
        text = text[:-1]
    return text + "..."


def draw_header(
    pdf: FPDF,
    *,
    org_name: str,
    org_lines: list[str],
    doc_title: str,
    doc_subtitle: str = "",
) -> None:
    """Full-bleed navy band: logo + organisation on the left, document
    title (gold) + subtitle on the right, gold accent rule underneath.
    Leaves the cursor just below the band."""
    pdf.set_fill_color(*NAVY)
    pdf.rect(0, 0, pdf.w, HEADER_H, style="F")
    pdf.set_fill_color(*GOLD)
    pdf.rect(0, HEADER_H, pdf.w, 1.2, style="F")

    x = pdf.l_margin
    if LOGO_PATH.exists():
        pdf.image(str(LOGO_PATH), x=x, y=9, w=16, h=16)
        x += 21

    right_w = 70
    left_w = pdf.w - pdf.r_margin - right_w - x - 4

    pdf.set_xy(x, 9.5)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(*WHITE)
    pdf.cell(left_w, 7, fit(pdf, org_name, left_w))

    pdf.set_font("Helvetica", "", 8)
    pdf.set_text_color(*NAVY_200)
    y = 17.5
    for line in [ln for ln in org_lines if ln][:3]:
        pdf.set_xy(x, y)
        pdf.cell(left_w, 4, fit(pdf, line, left_w))
        y += 4.2

    rx = pdf.w - pdf.r_margin - right_w
    pdf.set_xy(rx, 9)
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(*GOLD)
    pdf.cell(right_w, 9, safe(doc_title), align="R")
    if doc_subtitle:
        pdf.set_xy(rx, 19)
        pdf.set_font("Helvetica", "", 9.5)
        pdf.set_text_color(*WHITE)
        pdf.cell(right_w, 5, fit(pdf, doc_subtitle, right_w), align="R")

    pdf.set_text_color(0, 0, 0)
    pdf.set_xy(pdf.l_margin, HEADER_H + 10)


def eyebrow(pdf: FPDF, text: str, x: float, y: float, w: float = 0) -> None:
    """Small gold uppercase label used above values and sections."""
    pdf.set_xy(x, y)
    pdf.set_font("Helvetica", "B", 7)
    pdf.set_text_color(*GOLD_600)
    pdf.cell(w, 4, safe(text).upper())
    pdf.set_text_color(0, 0, 0)


def info_card(pdf: FPDF, title: str, body: str) -> None:
    """Rounded navy-50 card with an eyebrow title and multi-line body,
    full content width, starting at the current y."""
    w = pdf.w - pdf.l_margin - pdf.r_margin
    body = safe(body.strip())
    pdf.set_font("Helvetica", "", 9)
    lines = pdf.multi_cell(w - 12, 4.6, body, dry_run=True, output="LINES")
    h = 12 + 4.6 * max(1, len(lines)) + 4
    if pdf.get_y() + h > pdf.h - pdf.b_margin:
        pdf.add_page()
    y = pdf.get_y()
    pdf.set_fill_color(*NAVY_50)
    pdf.rect(pdf.l_margin, y, w, h, style="F", round_corners=True, corner_radius=3)
    eyebrow(pdf, title, pdf.l_margin + 6, y + 5)
    pdf.set_xy(pdf.l_margin + 6, y + 10.5)
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*NAVY_900)
    pdf.multi_cell(w - 12, 4.6, body)
    pdf.set_text_color(0, 0, 0)
    pdf.set_xy(pdf.l_margin, y + h + 4)
